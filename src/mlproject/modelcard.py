"""Generate ``docs/model_card.md`` from the cross-validation results, so the numbers cannot drift from the reports.

A model card says what a model is for, how well it did, and what it should not be trusted with. Every number here comes
from training-split cross-validation (or the pooled out-of-fold scores of the same folds). The test split is mentioned
only to say whether it has been used.
"""

from dataclasses import dataclass

import pandas as pd

RESULT_COLUMNS = ["pr_auc", "pr_auc_sd", "roc_auc", "brier"]


@dataclass(frozen=True)
class CardInputs:
    results: pd.DataFrame  # index = model label; columns RESULT_COLUMNS; row order is display order
    primary: str  # index label of the model the card describes
    penalty: str
    C: float
    calibration: dict[str, float]  # ece, slope, intercept, brier of the primary model on pooled out-of-fold scores
    cutoff: float
    at_cutoff: dict[str, float]  # tp, fp, fn, tn, precision, recall on pooled out-of-fold scores
    month_to_month_error_share: float
    month_to_month_customer_share: float
    n_train: int
    n_test: int
    prevalence: float
    n_features: int
    final_report_exists: bool


def results_table(inp: CardInputs) -> str:
    lines = ["| model | PR-AUC (mean ± sd over 5 folds) | ROC-AUC | Brier score |", "|---|---|---|---|"]
    for name, row in inp.results.to_dict("index").items():
        label = f"**{name}**" if name == inp.primary else str(name)
        sd = f" ± {row['pr_auc_sd']:.3f}" if pd.notna(row["pr_auc_sd"]) else ""
        roc = f"{row['roc_auc']:.3f}" if pd.notna(row["roc_auc"]) else "n/a"
        brier = f"{row['brier']:.3f}" if pd.notna(row["brier"]) else "n/a"
        lines.append(f"| {label} | {row['pr_auc']:.3f}{sd} | {roc} | {brier} |")
    return "\n".join(lines)


def render(inp: CardInputs) -> str:
    k, c = inp.at_cutoff, inp.calibration
    flagged = int(k["tp"] + k["fp"])
    total = int(flagged + k["fn"] + k["tn"])
    best_other = inp.results.drop(index=inp.primary)["pr_auc"].max()
    by_model = inp.results.to_dict("index")
    margin = by_model[inp.primary]["pr_auc"] - best_other
    primary_sd = by_model[inp.primary]["pr_auc_sd"]
    test_line = (
        "The test split has been evaluated once; see [`reports/final_test.md`](../reports/final_test.md)."
        if inp.final_report_exists
        else f"The {inp.n_test:,}-row test split has **not been used**. `python -m mlproject final` evaluates it once, when this phase is finished."
    )
    return f"""# Model card: customer churn classifier

*Generated by `python -m mlproject all` from the cross-validation results. Do not edit by hand.*

## The model

* **What it is:** {inp.penalty.upper()}-penalised logistic regression (C = {inp.C:g}) on {inp.n_features} customer attributes, after median
  imputation, `log(1 + x)` on `TotalCharges`, standardisation and one-hot encoding. It is the model that `python -m mlproject train` saves.
* **What it predicts:** the probability that a customer leaves the company (churns), from account and service attributes.
* **Why this one:** it has the highest cross-validated PR-AUC, but only by {margin:.3f} over the next best, which is smaller than the
  fold-to-fold spread (about {primary_sd:.3f}). It is chosen because it ties the more complex models and is
  the simplest and easiest to explain, not because it beat them.
* **Intended use:** ranking customers for a retention offer in a teaching or portfolio setting.
* **Not intended for:** decisions about individual customers without human review, pricing, credit, or any use outside this dataset's
  population (a public sample of 7,043 telecom customers). It has not been validated on any other data.

## Data

IBM's public Telco Customer Churn sample, split once into {inp.n_train:,} training and {inp.n_test:,} test rows (stratified, seed 42);
{inp.prevalence:.1%} of customers churned. See the [data card](data_card.md). All results below use training rows only.

## Results (5-fold cross-validation on the training split)

{results_table(inp)}

* PR-AUC is the primary metric because only about 1 customer in 4 churns; accuracy rewards a model that flags nobody.
* The gaps between the chosen models are within one fold standard deviation, so the table records a tie, not a ranking.
* {test_line}

## Behaviour at the saved decision cutoff

The default cutoff is {inp.cutoff:.2f}, the value that maximises F1 on out-of-fold training scores (`train --threshold` overrides it).
On those scores it flags {flagged:,} of {total:,} customers ({flagged / total:.0%}): precision {k['precision']:.2f} (about {k['precision']:.0%} of
flagged customers do churn) and recall {k['recall']:.2f} ({k['fn']:,.0f} churners are missed, {k['fp']:,.0f} non-churners are flagged).
F1 weights a missed churner and a false flag equally; a real retention budget would shift it.

## Calibration

On pooled out-of-fold scores the predicted probabilities are close to observed rates: expected calibration error {c['ece']:.3f}, calibration
slope {c['slope']:.2f}, intercept {c['intercept']:.2f}, Brier score {c['brier']:.3f}. The scores can be read as rough probabilities for this
population, not for a different one.

## Known weaknesses

* **Errors concentrate in one group.** Month-to-month customers are {inp.month_to_month_customer_share:.0%} of the training rows and account for
  {inp.month_to_month_error_share:.0%} of the mistakes at the cutoff. The churners it misses look like loyal customers.
* **Importance is not cause.** Permutation importance and coefficients describe this model's use of correlated inputs
  (`TotalCharges` overlaps `tenure` and `MonthlyCharges`); see [`reports/error_analysis.md`](../reports/error_analysis.md).
* **Sensitive attributes are inputs.** `gender` and `SeniorCitizen` are model inputs. No fairness audit has been done, so the
  model should not be used for decisions affecting individuals.
* **One dataset, one split, cross-validation only.** The numbers estimate performance on similar customers; they do not show behaviour
  under drift, a different market, or a changed offer.
* **A neural network and boosted trees did not beat it.** See [`reports/neural_network.md`](../reports/neural_network.md) and
  [`reports/gradient_boosting.md`](../reports/gradient_boosting.md).

## Using and versioning it

`python -m mlproject train` saves the model with a content-hash version and metadata; `predict` validates input rows before scoring and
`export` writes an ONNX copy checked against the pickle. See [`model_registry.md`](model_registry.md) for what is checked and what is not.
"""
